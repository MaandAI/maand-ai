import { jsPDF } from "jspdf";
import "jspdf-autotable";

export async function generateClinicalReportPDF(reportData: {
  title: string;
  userName: string;
  date: string;
  summary: string;
  emotionalTrends: string[];
  keyTopics: string[];
  recommendations: string[];
  riskAssessment: string;
}): Promise<Buffer> {
  const doc = new jsPDF() as any;
  const pageWidth = doc.internal.pageSize.getWidth();

  // Header
  doc.setFillColor(124, 58, 237); // Primary color
  doc.rect(0, 0, pageWidth, 40, "F");
  
  doc.setTextColor(255, 255, 255);
  doc.setFontSize(24);
  doc.setFont("helvetica", "bold");
  doc.text("Maand Clinical Report", 20, 25);
  
  doc.setFontSize(10);
  doc.text(`Generated on: ${reportData.date}`, pageWidth - 70, 25);

  // Content
  doc.setTextColor(30, 30, 30);
  doc.setFontSize(16);
  doc.text(reportData.title, 20, 55);
  
  doc.setFontSize(12);
  doc.setFont("helvetica", "normal");
  doc.text(`Patient Name: ${reportData.userName}`, 20, 65);

  // Summary
  doc.setFont("helvetica", "bold");
  doc.text("Executive Summary", 20, 80);
  doc.setFont("helvetica", "normal");
  const summaryLines = doc.splitTextToSize(reportData.summary, pageWidth - 40);
  doc.text(summaryLines, 20, 88);
  
  let currentY = 88 + (summaryLines.length * 7) + 10;

  // Emotional Trends
  doc.setFont("helvetica", "bold");
  doc.text("Emotional Trends", 20, currentY);
  currentY += 8;
  doc.setFont("helvetica", "normal");
  reportData.emotionalTrends.forEach((trend) => {
    doc.text(`• ${trend}`, 25, currentY);
    currentY += 7;
  });
  currentY += 5;

  // Key Topics
  doc.setFont("helvetica", "bold");
  doc.text("Key Topics Discussed", 20, currentY);
  currentY += 8;
  doc.setFont("helvetica", "normal");
  reportData.keyTopics.forEach((topic) => {
    doc.text(`• ${topic}`, 25, currentY);
    currentY += 7;
  });
  currentY += 5;

  // Recommendations
  doc.setFont("helvetica", "bold");
  doc.text("Recommendations", 20, currentY);
  currentY += 8;
  doc.setFont("helvetica", "normal");
  reportData.recommendations.forEach((rec) => {
    const recLines = doc.splitTextToSize(`• ${rec}`, pageWidth - 45);
    doc.text(recLines, 25, currentY);
    currentY += (recLines.length * 7);
  });
  currentY += 5;

  // Risk Assessment
  if (reportData.riskAssessment) {
    doc.setFont("helvetica", "bold");
    doc.text("Risk Assessment", 20, currentY);
    currentY += 8;
    doc.setFont("helvetica", "normal");
    const riskLines = doc.splitTextToSize(reportData.riskAssessment, pageWidth - 40);
    doc.text(riskLines, 20, currentY);
    currentY += (riskLines.length * 7);
  }

  // Footer
  doc.setFontSize(8);
  doc.setTextColor(150, 150, 150);
  doc.text("Disclaimer: This report is generated by Maand AI and is intended for informational purposes only.", 20, 285);

  const pdfBinary = doc.output();
  return Buffer.from(pdfBinary, "binary");
}
